export function questionText(lang: LuxLang, id: string, label: string): string {
  const t = TEMPLATE_QUESTIONS_ES[id]
  return lang === 'es' && t && t.en === label ? t.es : label
}

export function optionText(lang: LuxLang, questionId: string, option: string): string {
  if (lang !== 'es') return option
  if (option === 'Yes') return 'Sí'
  return TEMPLATE_QUESTIONS_ES[questionId]?.options?.[option] ?? option
}

export function documentLabel(lang: LuxLang, label: string): string {
  return lang === 'es' ? TEMPLATE_DOCUMENTS_ES[label]?.es ?? label : label
}

export function documentDescription(lang: LuxLang, description: string | null): string | null {
  if (!description || lang !== 'es') return description
  return TEMPLATE_DOC_DESCRIPTIONS_ES[description] ?? description
}
