/**
 * English / Spanish text for the pages families see (parish page, sign-up
 * forms, family page). The staff dashboard stays in English.
 *
 * Words the parish types (program names, descriptions, their own questions)
 * are shown as written; the built-in template questions and documents are
 * translated when the parish hasn't changed their wording.
 */

export type LuxLang = 'en' | 'es'
export const LUX_LANG_COOKIE = 'lux_lang'

export function parseLang(value: unknown): LuxLang | null {
  return value === 'es' ? 'es' : value === 'en' ? 'en' : null
}

/** Cookie first, then the browser's language */
export function resolveLang(cookie: string | undefined, acceptLanguage: string | null | undefined): LuxLang {
  const fromCookie = parseLang(cookie)
  if (fromCookie) return fromCookie
  return /^\s*es\b/i.test(acceptLanguage || '') ? 'es' : 'en'
}

